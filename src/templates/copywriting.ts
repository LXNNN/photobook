// ============ 随机抽取工具函数 ============
export function randomPick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * 根据文字元素类型随机获取文案
 * @param isBig 是否大标题
 * @param isSub 是否副标题
 * @param isShort 是否短句子（小文字位）
 */
export function getRandomText(isBig = false, isSub = false, isShort = false): string {
  if (isBig) return randomPick(BIG_TITLES);
  if (isSub) return randomPick(SUB_TITLES);
  if (isShort) return randomPick(SHORT_SENTENCES);
  return randomPick(SHORT_PARAGRAPHS);
}
